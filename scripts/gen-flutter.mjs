// Writes the Flutter package's glyphs from the core, so glyphs.json stays the
// one source. The tokens come from scripts/build-tokens.mjs. `--check` fails
// when the checked-in Dart file is out of date instead of writing it.
//
// Run from the repository root: node scripts/gen-flutter.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const core = new URL("../packages/core/", import.meta.url);
const out = new URL("../packages/flutter/lib/src/", import.meta.url);
const glyphs = JSON.parse(readFileSync(new URL("glyphs.json", core), "utf8"));

const RESERVED = new Set(["new", "switch", "default", "in", "is", "return", "continue", "class", "import", "export", "case", "do", "else", "for", "if", "null", "true", "false", "this", "var", "void", "with", "try", "throw", "super", "enum", "const", "final", "break", "assert", "catch", "extends", "finally", "rethrow", "while"]);
const glyphName = (name) => {
  const base = name.replace(/^Icon/, "");
  const n = base.charAt(0).toLowerCase() + base.slice(1);
  return RESERVED.has(n) ? `${n}Glyph` : n;
};
const raw = (s) => `r'''${s.replace(/\s+/g, " ").trim()}'''`;

const glyphDart = `// Generated by scripts/gen-flutter.mjs from packages/core/glyphs.json. Edit the
// assortment there and run the script; a change here is overwritten.

import 'glyph.dart';

/// The assortment, by meaning. An app maps its own label keys onto these, as
/// glyphs.md in the core describes.
abstract final class GlimGlyphs {
${glyphs.map((g) => `  /// ${g.means.replace(/\s+/g, " ")}\n  static const ${glyphName(g.name)} = GlimGlyphData('${g.name}', '${g.viewBox}', ${raw(g.svg)});`).join("\n")}

  /// Every glyph by its name in glyphs.json, such as \`IconSave\`.
  static const byName = <String, GlimGlyphData>{
${glyphs.map((g) => `    '${g.name}': ${glyphName(g.name)},`).join("\n")}
  };
}
`;

const files = [["glyphs.g.dart", glyphDart]];
if (process.argv.includes("--check")) {
  const stale = files.filter(([name, text]) => {
    try {
      return readFileSync(new URL(name, out), "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`out of date: ${stale.map(([n]) => n).join(", ")}; run node scripts/gen-flutter.mjs`);
    process.exit(1);
  }
} else {
  for (const [name, text] of files) writeFileSync(new URL(name, out), text);
}
console.log(`${glyphs.length} glyphs`);
