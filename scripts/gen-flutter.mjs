// Where a mode takes over: the OLED ramp, a light level or a motion level. A
// well's deeper field steps are read on their own below, the shapes come from
// build-tokens.mjs, and the contrast step stays with the stylesheet.
function applies(mode, at) {
  if (mode.name === "oled") return at.side === "oled";
  const light = mode.selector.match(/data-light/);
  if (light) return mode.selector.includes(`data-light="${at.light}"`);
  if (/data-motion/.test(mode.selector)) return !/dir=/.test(mode.selector) && mode.selector.includes(`data-motion='${at.motion}'`);
  return false;
}

/** A token's value on one side of the theme, at one light and motion level. */
function valueOf(group, name, at) {
  const t = token(group, name);
  const theme = ext(groups[group]).theme;
  const dark = at.side !== "light";
  let v = theme && dark ? (ext(t).dark ?? t.$value) : t.$value;
  for (const mode of ext(groups[group]).modes ?? []) {
    const mv = ext(t).modes?.[mode.name];
    if (mv === undefined || !applies(mode, at)) continue;
    v = mv !== null && typeof mv === "object" ? ((dark ? mv.dark : mv.light) ?? v) : mv;
  }
  return pickSide(String(v), at.side).replace(/\{([^.}]+)\.([^}]+)\}/g, (_, g, n) => valueOf(g, n, at));
}

/** The index of the parenthesis that closes the one at `open`. */
function closing(s, open) {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === "(") depth++;
    if (s[i] === ")" && --depth === 0) return i;
  }
  throw new Error(`unbalanced: ${s}`);
}

/** `s` split at the commas outside any parentheses. */
function topLevel(s, by = ",") {
  const parts = [""];
  let depth = 0;
  for (const ch of s) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === by && depth === 0) parts.push("");
    else parts[parts.length - 1] += ch;
  }
  return parts.map((p) => p.trim()).filter(Boolean);
}

function pickSide(s, side) {
  let at;
  while ((at = s.indexOf("light-dark(")) >= 0) {
    const open = at + "light-dark".length;
    const end = closing(s, open);
    const [light, dark] = topLevel(s.slice(open + 1, end));
    s = s.slice(0, at) + (side === "light" ? light : dark) + s.slice(end + 1);
  }
  return s;
}

const h2 = (n) => Math.round(n).toString(16).padStart(2, "0").toUpperCase();

/** A literal colour as a Dart Color, or null for anything worked out at run time. */
function dartColour(value) {
  const v = value.trim();
  if (v === "transparent") return "Color(0x00000000)";
  const hex = v.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (hex) return `Color(0x${(hex[2] ?? "FF").toUpperCase()}${hex[1].toUpperCase()})`;
  const rgb = v.match(/^rgba?\(([^()]*)\)$/);
  if (rgb) {
    const [r, g, b, a = "1"] = rgb[1].split(/[\s,/]+/).filter(Boolean);
    return `Color(0x${h2(Number(a) * 255)}${h2(r)}${h2(g)}${h2(b)})`;
  }
  const lch = v.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)$/);
  if (lch) {
    const [l, c, deg] = lch.slice(1, 4).map(Number);
    const rad = (deg * Math.PI) / 180;
    return `Color(0x${h2(Number(lch[4] ?? 1) * 255)}${srgbOf([l, c * Math.cos(rad), c * Math.sin(rad)]).slice(1)})`;
  }
  return null;
}

const length = (v) => {
  if (v === "0") return 0;
  const m = String(v).match(/^(-?[\d.]+)(rem|px)$/);
  if (!m) throw new Error(`not a length: ${v}`);
  return m[2] === "rem" ? Number(m[1]) * 16 : Number(m[1]);
};

/** A box-shadow list as GlimShadow layers, leaving out the ones that paint nothing. */
function shadows(value) {
  if (value === "none") return "<GlimShadow>[]";
  const layers = topLevel(value).flatMap((layer) => {
    const parts = topLevel(layer, " ");
    const inset = parts[0] === "inset";
    const rest = inset ? parts.slice(1) : parts;
    const lengths = [];
    while (rest.length && /^-?[\d.]+(px|rem)?$/.test(rest[0])) lengths.push(length(rest.shift()));
    const colour = dartColour(rest.join(" "));
    if (!colour) throw new Error(`cannot read the shadow colour in ${layer}`);
    if (colour.startsWith("Color(0x00")) return [];
    const [dx, dy, blur = 0, spread = 0] = lengths;
    const args = [colour];
    if (dx || dy) args.push(`offset: Offset(${num(dx)}, ${num(dy)})`);
    if (blur) args.push(`blur: ${num(blur)}`);
    if (spread) args.push(`spread: ${num(spread)}`);
    if (inset) args.push("inset: true");
    return [`GlimShadow(${args.join(", ")})`];
  });
  return `<GlimShadow>[${layers.join(", ")}]`;
}

/** A top-to-bottom linear-gradient(), or null for none. */
function gradient(value) {
  if (value === "none") return "null";
  const m = value.match(/^linear-gradient\((.*)\)$/);
  const [direction, ...stops] = m ? topLevel(m[1]) : [];
  if (direction !== "to bottom") throw new Error(`cannot draw ${value}`);
  const colours = [];
  const at = [];
  for (const stop of stops) {
    const pos = stop.match(/\s([\d.]+)%$/);
    colours.push(dartColour(pos ? stop.slice(0, pos.index) : stop));
    at.push(pos ? Number(pos[1]) / 100 : null);
  }
  at[0] ??= 0;
  at[at.length - 1] ??= 1;
  for (let i = 1; i < at.length; i++) {
    if (at[i] !== null) continue;
    let j = i;
    while (at[j] === null) j++;
    for (let k = i; k < j; k++) at[k] = at[i - 1] + ((at[j] - at[i - 1]) * (k - i + 1)) / (j - i + 1);
  }
  return `LinearGradient(begin: Alignment.topCenter, end: Alignment.bottomCenter, colors: [${colours.join(", ")}], stops: [${at.map(num).join(", ")}])`;
}

/** A CSS timing function as a Dart Curve. */
function curve(value) {
  if (value === "linear") return "Curves.linear";
  if (value === "ease") return "Curves.ease";
  const bezier = value.match(/^cubic-bezier\(([^)]*)\)$/);
  if (bezier) return `Cubic(${bezier[1].split(",").map(num).join(", ")})`;
  const points = value.match(/^linear\((.*)\)$/);
  if (!points) throw new Error(`cannot ease on ${value}`);
  const entries = topLevel(points[1]).map((e) => {
    const [v, p] = e.split(/\s+/);
    return { v: Number(v), t: p === undefined ? null : Number(p.replace("%", "")) / 100 };
  });
  entries[0].t ??= 0;
  entries[entries.length - 1].t ??= 1;
  for (let i = 1; i < entries.length; i++) {
    if (entries[i].t !== null) continue;
    let j = i;
    while (entries[j].t === null) j++;
    for (let k = i; k < j; k++) entries[k].t = entries[i - 1].t + ((entries[j].t - entries[i - 1].t) * (k - i + 1)) / (j - i + 1);
  }
  return `GlimLinearCurve([${entries.flatMap((e) => [num(e.t), num(e.v)]).join(", ")}])`;
}

const duration = (v) => {
  const m = v.match(/^([\d.]+)(m?s)$/);
  if (!m) throw new Error(`not a duration: ${v}`);
  const ms = m[2] === "s" ? Number(m[1]) * 1000 : Number(m[1]);
  return ms === 0 ? "Duration.zero" : `Duration(milliseconds: ${num(ms)})`;
};

